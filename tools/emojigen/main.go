// Command emojigen writes the emoji catalog of internal/feature/emoji from
// the data the Rust app uses, so names, shortcodes, keywords, and
// translations stay identical: the emojis crate (its generated tables) and
// the CLDR tables in src-tauri/data/emoji that scripts/emoji-data.ts writes.
//
// Run it from the module root while the Rust app exists:
//
//	go run ./tools/emojigen
//
// It finds the crate with `cargo metadata`; -crate names its folder instead.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"slices"
	"strconv"
	"strings"
)

// The skin tones in the crate's order: an emoji's tone is its offset from
// the default-tone emoji.
var skinTones = []string{
	"Default", "Light", "MediumLight", "Medium", "MediumDark", "Dark",
	"LightAndMediumLight", "LightAndMedium", "LightAndMediumDark", "LightAndDark",
	"MediumLightAndLight", "MediumLightAndMedium", "MediumLightAndMediumDark", "MediumLightAndDark",
	"MediumAndLight", "MediumAndMediumLight", "MediumAndMediumDark", "MediumAndDark",
	"MediumDarkAndLight", "MediumDarkAndMediumLight", "MediumDarkAndMedium", "MediumDarkAndDark",
	"DarkAndLight", "DarkAndMediumLight", "DarkAndMedium", "DarkAndMediumDark",
}

var (
	emojiLine = regexp.MustCompile(`^\s*Emoji \{ emoji: "([^"\\]*)", name: "([^"\\]*)", emoji_version: [^}]*\}, group: Group::\w+, skin_tone: (?:None|Some\(\((\d+), (\d+), SkinTone::(\w+)\)\)), shortcodes: (?:None|Some\(&\[([^\]]*)\]\)) \},$`)
	quoted    = regexp.MustCompile(`"([^"\\]*)"`)
	mapEntry  = regexp.MustCompile(`\("([^"\\]*)",(\d+)\)`)
	version   = regexp.MustCompile(`UnicodeVersion::new\((\d+), (\d+)\);`)
)

func main() {
	crate := flag.String("crate", "", "folder of the emojis crate (default: from cargo metadata)")
	data := flag.String("data", "src-tauri/data/emoji", "folder of the CLDR tables")
	out := flag.String("out", "internal/feature/emoji", "package folder to write")
	flag.Parse()
	if *crate == "" {
		*crate = findCrate()
	}
	if err := run(*crate, *data, *out); err != nil {
		log.Fatal(err)
	}
}

func findCrate() string {
	cmd := exec.Command("cargo", "metadata", "--manifest-path", "src-tauri/Cargo.toml", "--format-version", "1", "--locked")
	cmd.Stderr = os.Stderr
	output, err := cmd.Output()
	if err != nil {
		log.Fatalf("cargo metadata: %v", err)
	}
	var meta struct {
		Packages []struct {
			Name         string `json:"name"`
			ManifestPath string `json:"manifest_path"`
		} `json:"packages"`
	}
	if err := json.Unmarshal(output, &meta); err != nil {
		log.Fatal(err)
	}
	for _, p := range meta.Packages {
		if p.Name == "emojis" {
			return filepath.Dir(p.ManifestPath)
		}
	}
	log.Fatal("cargo metadata lists no emojis crate")
	return ""
}

func run(crate, data, out string) error {
	gen, err := os.ReadFile(filepath.Join(crate, "src", "gen", "mod.rs"))
	if err != nil {
		return err
	}
	unicodeMap, err := os.ReadFile(filepath.Join(crate, "src", "gen", "unicode.rs"))
	if err != nil {
		return err
	}
	manifest, err := os.ReadFile(filepath.Join(crate, "Cargo.toml"))
	if err != nil {
		return err
	}
	crateVersion := regexp.MustCompile(`(?m)^version = "([^"]+)"`).FindSubmatch(manifest)
	unicodeVersion := version.FindSubmatch(gen)
	if crateVersion == nil || unicodeVersion == nil {
		return fmt.Errorf("%s: no crate or Unicode version", crate)
	}

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by tools/emojigen from the emojis crate %s (Unicode %s.%s). DO NOT EDIT.\n",
		crateVersion[1], unicodeVersion[1], unicodeVersion[2])
	b.WriteString("// Regenerate from the module root, while the Rust app exists: go run ./tools/emojigen\n")
	b.WriteString("// The data is (MIT OR Apache-2.0) AND Unicode-3.0, as the crate is; data/LICENSE has the Unicode license.\n\n")
	b.WriteString("package emoji\n\n")
	b.WriteString("var catalog = []emoji{\n")
	glyphs := map[string]int{}
	inTable := false
	for line := range strings.SplitSeq(string(gen), "\n") {
		switch {
		case strings.HasPrefix(line, "pub const EMOJIS: &[Emoji] = &["):
			inTable = true
			continue
		case !inTable:
			continue
		case line == "];":
			inTable = false
			continue
		}
		m := emojiLine.FindStringSubmatch(line)
		if m == nil {
			return fmt.Errorf("unexpected line in the emoji table: %s", line)
		}
		glyph, name, base, count, tone, codes := m[1], m[2], m[3], m[4], m[5], m[6]
		var shortcodes []string
		for _, c := range quoted.FindAllStringSubmatch(codes, -1) {
			shortcodes = append(shortcodes, strconv.Quote(c[1]))
		}
		tones := "tones{}"
		if base != "" {
			offset := slices.Index(skinTones, tone)
			if offset < 0 {
				return fmt.Errorf("%s: unknown skin tone %s", glyph, tone)
			}
			tones = fmt.Sprintf("tones{%s, %s, %d}", base, count, offset)
		}
		codeList := "nil"
		if len(shortcodes) > 0 {
			codeList = "[]string{" + strings.Join(shortcodes, ", ") + "}"
		}
		glyphs[glyph] = len(glyphs)
		fmt.Fprintf(&b, "\t{%s, %s, %s, %s},\n", strconv.Quote(glyph), strconv.Quote(name), codeList, tones)
	}
	b.WriteString("}\n\n")
	if len(glyphs) == 0 {
		return fmt.Errorf("%s: no emoji table", crate)
	}

	b.WriteString("// variants maps the other forms that emojis::get accepts, such as an\n// emoji without its variation selector, to its catalog index.\n")
	b.WriteString("var variants = map[string]int{\n")
	entries := mapEntry.FindAllStringSubmatch(string(unicodeMap), -1)
	if len(entries) < len(glyphs) {
		return fmt.Errorf("%s: the lookup map has %d entries for %d emoji", crate, len(entries), len(glyphs))
	}
	var lines []string
	for _, e := range entries {
		index, _ := strconv.Atoi(e[2])
		if i, ok := glyphs[e[1]]; ok && i == index {
			continue
		}
		lines = append(lines, fmt.Sprintf("\t%s: %d,\n", strconv.Quote(e[1]), index))
	}
	// The crate lists them in hash order; sorted, a regeneration diffs well.
	slices.Sort(lines)
	b.WriteString(strings.Join(lines, ""))
	b.WriteString("}\n")

	source, err := format.Source(b.Bytes())
	if err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(out, "catalog.go"), source, 0o644); err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Join(out, "data"), 0o755); err != nil {
		return err
	}
	for _, name := range []string{"zh.tsv", "ms.tsv", "es.tsv", "LICENSE"} {
		content, err := os.ReadFile(filepath.Join(data, name))
		if err != nil {
			return err
		}
		if err := os.WriteFile(filepath.Join(out, "data", name), content, 0o644); err != nil {
			return err
		}
	}
	return nil
}
